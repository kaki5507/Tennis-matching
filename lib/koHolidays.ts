export type DayKind = { kind: "weekday" | "weekend" | "holiday"; name?: string }

/** date: YYYY-MM-DD → 평일 / 주말 / 공휴일 */
export function dayKind(date: string): DayKind {
  const holiday = HOLIDAYS[date]
  if (holiday) return { kind: "holiday", name: holiday }
  const [y, m, d] = date.split("-").map(Number)
  const dow = new Date(Date.UTC(y, m - 1, d)).getUTCDay()
  if (dow === 0 || dow === 6) return { kind: "weekend", name: dow === 0 ? "일요일" : "토요일" }
  return { kind: "weekday" }
}
